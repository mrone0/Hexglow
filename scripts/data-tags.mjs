// 效果文本的启发式分类；标签表达相关收益，不把明确的代价/条件当成增益。
const TAG_RULES = [
  ['ad', /(攻击力|物理伤害|穿甲|护甲穿透|护甲(?:和魔法抗性)?击碎|自适应之力.*攻击)/],
  ['ap', /(法术强度|魔法伤害|法术穿透|魔法抗性击碎)/],
  ['as', /(攻击速度|每秒攻击)/],
  ['crit', /(暴击)/],
  ['onhit', /(攻击特效|普攻|下一次攻击|攻击时|命中效果)/],
  ['haste', /(技能急速|冷却时间|冷却缩减|终极技能急速)/],
  ['hp', /(最大生命|生命值|额外生命)/],
  ['sustain', /(生命偷取|吸血|治疗|回复|全能吸血|护盾)/],
  ['tank', /(护甲(?!穿透|(?:和魔法抗性)?击碎)|魔法抗性(?!穿透|击碎)|减伤|免伤|伤害减免|体型)/],
  ['mobility', /(移动速度|位移|冲刺|突进|雪球|闪现|施法距离)/],
  ['cc', /(击飞|眩晕|减速|嘲讽|禁锢|恐惧|定身|沉默|缴械)/],
  ['summoner', /(召唤师技能|雪球|闪现|屏障|治疗术|点燃|虚弱)/],
  ['ultimate', /(终极技能|你的大招|施放你的终极)/],
  ['economy', /(金币|金币数量|商店|出售|装备格|经验值|升级)/],
  ['mana', /(法力|法力值|法力消耗)/],
  ['stack', /(叠加|层数|永久获得|每层)/],
  ['range', /(攻击距离|射程)/],
];

const CATEGORY_RULES = [
  ['damage', /(伤害|暴击|穿甲|护甲穿透|法术穿透|护甲(?:和魔法抗性)?击碎|魔法抗性击碎|法术强度|攻击力|攻击速度|处决|飞弹)/],
  ['defense', /(生命值|护甲(?!穿透|(?:和魔法抗性)?击碎)|魔法抗性(?!穿透|击碎)|减伤|免伤|治疗|护盾|回复|韧性|体型)/],
  ['utility', /(移动速度|技能急速|冷却|召唤师技能|控制|视野|刷新|距离)/],
  ['economy', /(金币|商店|装备格|经验)/],
];

// 只处理原文能明确判定方向的短语。原始 effect 始终保留，供模型与用户核对限制。
// 没有在这里推断英雄机制、数值或“指定技能”的实际身份。
function benefitText(effect) {
  return String(effect || '')
    .replace(/不能使用(?:你的)?终极技能|非终极技能/g, '')
    .replace(/你造成的伤害(?:降低|减少)\s*\d+(?:\.\d+)?%/g, '')
    .replace(/受到伤害后失效\s*\d+(?:\.\d+)?秒/g, '')
    .replace(/对敌方英雄造成伤害后/g, '')
    .replace(/减少\s*\d+(?:\.\d+)?%最大生命值/g, '')
    .replace(/低生命值|生命值最低|目标生命值|他们当前生命值/g, '')
    .replace(/将(?:你的所有|额外)?(?:攻击力|法术强度|攻击速度)转化为/g, '')
    .replace(/移动速度降低(?:额外的)?\s*\d+(?:\.\d+)?/g, '')
    .replace(/减速抗性/g, '')
    // 自身/每目标触发间隔是限制，不是给英雄技能提供急速。
    .replace(/每(?:个目标|个敌人|名敌人)(?:有|具有)\s*\d+(?:\.\d+)?秒冷却时间/g, '')
    .replace(/免疫伤害/g, '免伤');
}

export function deriveTags(effect) {
  const text = benefitText(effect);
  const tags = TAG_RULES.filter(([, pattern]) => pattern.test(text)).map(([tag]) => tag);
  // 输入属性决定缩放，不代表输出伤害：例如每点 AP 提供护盾。
  const categoryText = text.replace(/每拥有\s*\d+(?:\.\d+)?(?:法术强度|攻击力|最大生命值)(?:就会)?(?:获得|提供)/g, '获得');
  const scored = CATEGORY_RULES.map(([category, pattern]) => [
    category,
    [...categoryText.matchAll(new RegExp(pattern.source, 'g'))].length,
  ]).sort((a, b) => b[1] - a[1]);
  const category = scored[0]?.[1] > 0 ? scored[0][0] : 'utility';
  return {category, tags};
}
